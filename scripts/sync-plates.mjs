/**
 * Writes lib/generated.ts from whatever plates actually exist on disk.
 * A seed without a file falls back to a seeded placeholder, so a partial
 * generation run degrades slot by slot instead of breaking the build.
 *
 *   node scripts/sync-plates.mjs
 */

import fs from "node:fs";
import path from "node:path";

const DIR = path.resolve("public/plates");
const OUT = path.resolve("lib/generated.ts");

const seeds = fs.existsSync(DIR)
  ? fs
      .readdirSync(DIR)
      .filter((f) => f.endsWith(".webp"))
      .map((f) => f.replace(/\.webp$/, ""))
      .sort()
  : [];

fs.writeFileSync(
  OUT,
  `/**
 * Seeds that have a committed house plate at /plates/<seed>.webp.
 * Regenerated by scripts/sync-plates.mjs — do not edit by hand.
 */
export const GENERATED = new Set<string>([
${seeds.map((s) => `  ${JSON.stringify(s)},`).join("\n")}
]);
`,
);

console.log(`sync-plates: ${seeds.length} plates`);
